import { expect, test } from '@playwright/test'

test('Help opens accessible dialogs and links to GitHub', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await expect(page.locator('.menu-surface').getByRole('link', { name: 'GitHub', exact: true })).toHaveAttribute('href', 'https://github.com/photolisa/photolisa')
  await page.getByRole('button', { name: 'About', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'About Photolisa' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Help', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await page.getByRole('button', { name: 'Keyboard Shortcuts', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Keyboard Shortcuts' })).toContainText('Ctrl+Shift+Tab')
  await page.keyboard.press('Control+n')
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('Home keeps open documents and restores the selected project', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByLabel('Document canvas')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'Add project tab' }).click()
  await page.getByLabel('Name', { exact: true }).fill('Keep my project')
  await page.getByLabel('Width (px)').fill('320')
  await page.getByLabel('Height (px)').fill('240')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  const project = page.getByRole('tab', { name: /Keep my project/ })
  await expect(project).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Home', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('tab', { name: 'Home', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: 'Start blank canvas' })).toBeVisible()
  await expect(project).toHaveAttribute('aria-selected', 'false')
  await project.click()
  await expect(project).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByText('320 × 240 px').first()).toBeVisible()
  await expect(page.locator('[data-layer-row]')).toHaveCount(1)
})
