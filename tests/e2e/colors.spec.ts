import { expect, test } from '@playwright/test'

test('foreground/background picker, shortcuts, swatches, and IndexedDB recovery', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByLabel('Document canvas')).toBeVisible({ timeout: 60_000 })
  const foreground = page.getByRole('button', { name: 'Foreground color picker' })
  const background = page.getByRole('button', { name: 'Background color picker' })
  await expect(foreground).toBeVisible({ timeout: 60_000 })
  await foreground.click()
  await page.getByLabel('HEX color').fill('#12AB3480')
  await page.getByRole('dialog', { name: 'foreground color picker' }).getByRole('button', { name: 'Apply' }).click()
  await expect(foreground).toHaveAttribute('title', /#12AB3480/)
  await background.click()
  await page.getByRole('tab', { name: 'RGBA' }).click()
  await page.getByLabel('A channel').fill('0')
  await page.getByLabel('A channel').press('Tab')
  await page.getByRole('dialog', { name: 'background color picker' }).getByRole('button', { name: 'Apply' }).click()
  await expect(background).toHaveAttribute('title', /#FFFFFF00/)
  await page.keyboard.press('x')
  await expect(foreground).toHaveAttribute('title', /#FFFFFF00/)
  await page.keyboard.press('d')
  await expect(foreground).toHaveAttribute('title', /#000000FF/)
  await expect(background).toHaveAttribute('title', /#FFFFFFFF/)

  await foreground.click()
  await page.getByLabel('HEX color').fill('#446688CC')
  await page.getByRole('dialog', { name: 'foreground color picker' }).getByRole('button', { name: 'Apply' }).click()
  await page.getByRole('button', { name: 'Swatches', exact: true }).click()
  await page.getByRole('button', { name: 'Add foreground to favorites' }).click()
  await page.getByLabel('Create collection name').fill('Brand')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByLabel('New swatch name').fill('Blue slate')
  await page.getByRole('button', { name: 'Add foreground to collection' }).click()
  await expect(page.getByRole('button', { name: 'Collection color Blue slate' })).toBeVisible()
  await page.reload()
  await expect(foreground).toHaveAttribute('title', /#446688CC/, { timeout: 60_000 })
  await page.getByRole('button', { name: 'Swatches', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Favorite #446688CC' })).toBeVisible()
  await page.getByLabel('Swatch collection').selectOption({ label: 'Brand' })
  await expect(page.getByRole('button', { name: 'Collection color Blue slate' })).toBeVisible()
  await foreground.click()
  await page.getByRole('tab', { name: 'HSL' }).click()
  await page.getByLabel('H channel').fill('120')
  await page.getByLabel('H channel').press('Tab')
  await page.getByRole('dialog', { name: 'foreground color picker' }).getByRole('button', { name: 'Apply' }).click()
  await expect(foreground).not.toHaveAttribute('title', /#446688CC/)
  await foreground.click()
  await page.getByRole('tab', { name: 'RGB', exact: true }).click()
  await page.getByLabel('R channel').fill('255')
  await page.getByLabel('R channel').press('Tab')
  await page.getByRole('dialog', { name: 'foreground color picker' }).getByRole('button', { name: 'Apply' }).click()
  await expect(foreground).toHaveAttribute('title', /#FF[0-9A-F]{6}/)
  await foreground.click()
  const dialog = page.getByRole('dialog', { name: 'foreground color picker' })
  await dialog.getByRole('button', { name: 'Apply', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Close color picker' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Apply', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'foreground color picker' })).toHaveCount(0)
  await expect(foreground).toBeFocused()
})
