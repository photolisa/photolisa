import { selectEditorTool } from './helpers/tools'
import { expect, test } from '@playwright/test'

test('drag creates editable shape, Escape cancels, properties and rasterization are undoable', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByLabel('Document canvas')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'File', exact: true }).click()
  await page.getByRole('button', { name: /New document/ }).click()
  await page.getByLabel('Name').fill('Shape Test')
  await page.getByLabel('Width (px)').fill('300')
  await page.getByLabel('Height (px)').fill('200')
  await page.getByRole('button', { name: 'Create' }).click()
  const bounds = await page.getByLabel('Document canvas').boundingBox()
  if (!bounds) throw new Error('Canvas not laid out')
  const x = bounds.x + bounds.width / 2
  const y = bounds.y + bounds.height / 2
  await page.getByRole('button', { name: 'Rectangle tool', exact: true }).click()
  await page.mouse.move(x - 35, y - 25)
  await page.mouse.down()
  await page.mouse.move(x + 35, y + 25, { steps: 4 })
  await page.mouse.up()
  await expect(page.getByLabel('Vector geometry')).toContainText('rect geometry')
  await page.getByLabel('Shape width').fill('100')
  await page.getByLabel('Shape width').press('Tab')
  await expect(page.getByLabel('Shape width')).toHaveValue('100')
  await page.getByLabel('Shape rotation').fill('30')
  await page.getByLabel('Shape rotation').press('Tab')
  await expect(page.getByLabel('Shape rotation')).toHaveValue('30')
  await page.getByRole('button', { name: 'Rasterize shape' }).click()
  await expect(page.getByLabel('Vector geometry')).toHaveCount(0)
  await page.keyboard.press('Control+z')
  await expect(page.getByLabel('Vector geometry')).toContainText('rect geometry')
  await selectEditorTool(page, 'Ellipse tool')
  await page.mouse.move(x - 15, y - 15)
  await page.mouse.down()
  await page.mouse.move(x + 20, y + 20)
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Vector geometry')).toContainText('rect geometry')
})

test('line and variable-sided polygon are usable vector tools', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByLabel('Document canvas')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'File', exact: true }).click()
  await page.getByRole('button', { name: /New document/ }).click()
  await page.getByLabel('Name').fill('Lines')
  await page.getByLabel('Width (px)').fill('300')
  await page.getByLabel('Height (px)').fill('200')
  await page.getByRole('button', { name: 'Create' }).click()
  const box = await page.getByLabel('Document canvas').boundingBox()
  if (!box) throw new Error('Canvas unavailable')
  const x = box.x + box.width / 2; const y = box.y + box.height / 2
  await selectEditorTool(page, 'Line tool')
  await page.mouse.move(x - 30, y - 20); await page.mouse.down(); await page.mouse.move(x + 30, y + 20); await page.mouse.up()
  await expect(page.getByLabel('Vector geometry')).toContainText('line geometry')
  await selectEditorTool(page, 'Polygon tool')
  await page.getByLabel('Polygon sides').fill('7')
  await page.mouse.move(x - 25, y - 20); await page.mouse.down(); await page.mouse.move(x + 25, y + 20); await page.mouse.up()
  await expect(page.getByLabel('Vector geometry')).toContainText('polygon geometry')
  await page.keyboard.press('Control+z')
  await expect(page.getByLabel('Vector geometry')).toContainText('line geometry')
})
