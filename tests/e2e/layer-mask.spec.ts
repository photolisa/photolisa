import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('selection mask previews, exports, paints, and survives undo', async ({ page }) => {
  await page.addInitScript(() => { Object.defineProperty(window, 'showSaveFilePicker', { value: undefined }) })
  await page.goto('/')
  await expect(page.getByLabel('Document canvas')).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'File' }).click()
  await page.getByRole('button', { name: 'New document…' }).click()
  await page.getByLabel('Width (px)').fill('64'); await page.getByLabel('Height (px)').fill('64')
  await page.getByRole('button', { name: 'Create' }).click(); await page.keyboard.press('Control+1')
  await page.keyboard.press('Control+a')
  await page.getByRole('button', { name: 'Edit' }).click(); await page.getByRole('button', { name: 'Fill selection' }).click()
  await page.keyboard.press('Control+d')
  const box = await page.getByLabel('Document canvas').boundingBox()
  if (!box) throw new Error('Document canvas unavailable')
  const center = { x: box.x + box.width / 2, y: box.y + box.height / 2 }
  await page.getByRole('button', { name: 'Rectangle selection tool' }).click()
  await page.mouse.move(center.x - 10, center.y - 10); await page.mouse.down(); await page.mouse.move(center.x + 10, center.y + 10); await page.mouse.up()
  await page.getByRole('button', { name: 'Reveal selection' }).click()
  expect(await alphaAt(page, 32, 32)).toBe(255)
  expect(await alphaAt(page, 5, 5)).toBe(0)
  await page.getByRole('button', { name: 'Invert', exact: true }).click()
  expect(await alphaAt(page, 32, 32)).toBe(0)
  await page.keyboard.press('Control+z')
  expect(await alphaAt(page, 32, 32)).toBe(255)
  await page.keyboard.press('Control+d')
  await page.getByRole('button', { name: 'Brush tool' }).click()
  await page.mouse.click(center.x, center.y)
  expect(await alphaAt(page, 32, 32)).toBe(0)
  await page.keyboard.press('Control+z')
  expect(await alphaAt(page, 32, 32)).toBe(255)
  await page.getByRole('button', { name: 'File' }).click()
  const projectDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: /Save project/ }).click()
  const projectPath = await (await projectDownload).path()
  if (!projectPath) throw new Error('Project download unavailable')
  await page.locator('input[type=file]').setInputFiles({ name: 'masked.photolisa', mimeType: 'application/x-photolisa', buffer: await readFile(projectPath) })
  expect(await alphaAt(page, 32, 32)).toBe(255)
  expect(await alphaAt(page, 5, 5)).toBe(0)
})

